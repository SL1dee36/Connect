package com.connect.app.data.locale

import java.util.Locale

object LocalizationManifest {

    val supportedLanguages = listOf(
        AppLanguage.SYSTEM,
        AppLanguage.RU,
        AppLanguage.EN,
        AppLanguage.DE,
        AppLanguage.ES,
        AppLanguage.BE
    )

    fun getStrings(language: AppLanguage, systemLocale: Locale = Locale.getDefault()): AppStrings {
        return when (language) {
            AppLanguage.RU -> RussianStrings
            AppLanguage.EN -> EnglishStrings
            AppLanguage.DE -> GermanStrings
            AppLanguage.ES -> SpanishStrings
            AppLanguage.BE -> BelarusianStrings
            AppLanguage.SYSTEM -> {
                when (systemLocale.language.lowercase()) {
                    "ru" -> RussianStrings
                    "be" -> BelarusianStrings
                    "de" -> GermanStrings
                    "es" -> SpanishStrings
                    else -> EnglishStrings
                }
            }
        }
    }
}

